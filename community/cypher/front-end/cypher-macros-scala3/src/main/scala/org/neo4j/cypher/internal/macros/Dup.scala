package org.neo4j.cypher.internal.macros

import scala.quoted.Expr
import scala.quoted.Quotes
import scala.quoted.Type
import scala.quoted.quotes
import scala.reflect.ClassTag

/**
 * Type class for reconstructing a case class instance from rewritten children, in the shape the
 * Rewritable framework's `dup(children)` contract needs.
 *
 * The instance is generated by a macro at the summoning site, as a direct constructor call with
 * one statically typed cast per parameter. This serves the same purpose as
 * `Mirror.ProductOf[A]#fromProduct` but also supports case classes with more than one parameter
 * list, which the compiler generates no `Mirror` for. Later parameter lists are not part of the
 * product children that rewriters traverse, so their values are copied over from the original
 * instance. That requires each later-list parameter to be a `val`.
 *
 * Constructor parameters with a reified array type get their element type restored via
 * [[Dup.castArray]], because rewriters rebuild changed array children as `Array[AnyRef]`.
 *
 * Derivation is rejected at compile time for classes that are not case classes, take type
 * parameters, are nested in a class or trait (their constructor needs an outer instance), or
 * have a later-list parameter that is not a `val`.
 */
trait Dup[A] {

  /**
   * Reconstruct `a` with the given children as the first constructor parameter list.
   * Children must have the same arity and runtime types as `a.productIterator`.
   */
  def dup(a: A, children: Seq[AnyRef]): A
}

object Dup {

  inline given derived[A <: Product]: Dup[A] = ${ DupMacro.derivedImpl[A] }

  /**
   * Restore the reified element type of an array child. Rewriters rebuild changed array children
   * as `Array[AnyRef]` (see `Rewritable.dupAny`), which cannot be passed to a constructor
   * parameter of a more specific array type.
   */
  def castArray[T](x: AnyRef)(implicit ct: ClassTag[T]): Array[T] = {
    val target = ct.runtimeClass
    val component = x.getClass.getComponentType
    if (component != null && target.isAssignableFrom(component)) {
      x.asInstanceOf[Array[T]]
    } else {
      val src = x.asInstanceOf[Array[AnyRef]]
      val dst = ct.newArray(src.length)
      var i = 0
      while (i < src.length) {
        dst(i) = src(i).asInstanceOf[T]
        i += 1
      }
      dst
    }
  }
}

object DupMacro {

  def derivedImpl[A <: Product : Type](using Quotes): Expr[Dup[A]] = {
    import quotes.reflect.*

    val tpe = TypeRepr.of[A].dealias
    val sym = tpe.typeSymbol

    if (!sym.flags.is(Flags.Case)) {
      report.errorAndAbort(s"Dup can only be derived for case classes, but ${sym.fullName} is not one")
    }
    if (tpe.typeArgs.nonEmpty) {
      report.errorAndAbort(s"Dup cannot be derived for type-parameterized case class ${sym.fullName}")
    }
    val owner = sym.maybeOwner
    if (!(owner.isPackageDef || owner.flags.is(Flags.Module))) {
      report.errorAndAbort(
        s"Dup can only be derived for top-level case classes or case classes nested in objects, " +
          s"but ${sym.fullName} is nested in ${owner.fullName} and its constructor needs an outer instance"
      )
    }

    val ctor = sym.primaryConstructor
    val paramLists: List[List[Symbol]] = ctor.paramSymss.filterNot(_.exists(_.isTypeParam))
    val firstList = paramLists.head
    val laterLists = paramLists.tail

    laterLists.flatten.foreach { p =>
      val field = sym.fieldMember(p.name)
      // A non-val parameter that is captured by the class body still creates a field, but a
      // private one that the generated constructor call could not read.
      if (!field.exists || field.flags.is(Flags.Private) || field.flags.is(Flags.Protected)) {
        report.errorAndAbort(
          s"Dup cannot be derived for ${sym.fullName}: parameter ${p.name} in a later parameter list " +
            s"must be a val so its value can be copied from the original instance"
        )
      }
    }

    def constructorArg(children: Expr[Seq[AnyRef]], index: Int, param: Symbol): Term = {
      val paramType = tpe.memberType(param).dealias
      val childExpr = '{ $children(${ Expr(index) }) }
      paramType.asType match {
        case '[t] =>
          if (paramType.classSymbol.contains(defn.ArrayClass) && !(paramType =:= TypeRepr.of[Array[AnyRef]])) {
            paramType.typeArgs.head.asType match {
              case '[e] =>
                Expr.summon[ClassTag[e]] match {
                  case Some(classTag) => '{ Dup.castArray[e]($childExpr)(using $classTag) }.asTerm
                  case None =>
                    report.errorAndAbort(
                      s"Dup: no ClassTag for array element type ${paramType.typeArgs.head.show} " +
                        s"of parameter ${param.name} in ${sym.fullName}"
                    )
                }
            }
          } else {
            '{ $childExpr.asInstanceOf[t] }.asTerm
          }
      }
    }

    def construct(a: Expr[A], children: Expr[Seq[AnyRef]]): Expr[A] = {
      val newTerm = Select(New(Inferred(tpe)), ctor)
      val firstArgs = firstList.zipWithIndex.map { case (p, i) => constructorArg(children, i, p) }
      val laterArgs = laterLists.map(_.map(p => Select.unique(a.asTerm, p.name)))
      laterArgs.foldLeft(Apply(newTerm, firstArgs))((acc, args) => Apply(acc, args)).asExprOf[A]
    }

    '{
      new Dup[A] {
        override def dup(a: A, children: Seq[AnyRef]): A = ${ construct('a, 'children) }
      }
    }
  }
}
